import fs from 'node:fs';
import * as H from '../../work/native-v36/headless.mjs';
export {H};
export const root=new URL('../../work/comps-tempo-v36/',import.meta.url);
fs.mkdirSync(root,{recursive:true});
export const data=JSON.parse(fs.readFileSync(new URL('../../work/native-v36/data.json',import.meta.url)));
export const meta=JSON.parse(fs.readFileSync(new URL('meta.json',root)));
if(data.rules!==36||data.identity!==H.identity)throw Error('Matching verified rules-36 inputs required');
export const roster=Object.fromEntries(data.roster.map(r=>[r.id,r]));
export const items=Object.fromEntries(data.items.map(r=>[r.id,r]));
export const family=line=>H.roster.l(line);
export const code=g=>g.round.stage*10+g.round.r;
export const copies=(s,line)=>Object.values(s.units).filter(u=>family(u.line)===family(line)).reduce((n,u)=>n+3**(u.star-1),0);
export const exactCopies=(s,line)=>Object.values(s.units).filter(u=>u.line===line).reduce((n,u)=>n+3**(u.star-1),0);
export const army=s=>H.shop.u(s).map(u=>({line:u.line,star:u.star,items:[...(u.items??[])],cell:u.cell}));
export const mass=s=>Object.values(s.units).flatMap(u=>u.items??[]).reduce((n,id)=>n+(items[id]?.kind==='full'?2:items[id]?.kind==='part'?1:0),0);
export const mean=xs=>xs.length?xs.reduce((a,b)=>a+b,0)/xs.length:null;
export const quantile=(xs,p)=>{if(!xs.length)return null;const a=[...xs].sort((a,b)=>a-b),i=(a.length-1)*p,k=Math.floor(i);return a[k]+(a[Math.min(k+1,a.length-1)]-a[k])*(i-k);};
export const hash=H.hash;
export const write=(name,value)=>fs.writeFileSync(new URL(name,root),JSON.stringify(value,null,2)+'\n');
export const read=name=>JSON.parse(fs.readFileSync(new URL(name,root)));
