import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {applyProgressionPlans} from './progression-plans.mjs';
const html=fs.readFileSync('compositions.html','utf8');
const read=k=>JSON.parse(html.match(new RegExp(`window\\.${k}=(\\{[^\\n]*\\});`))[1]);
const comps=read('KANTO_COMPS'),guides=read('KANTO_GUIDES').guides;
const roster=Object.fromEntries(read('KANTO_DATA').roster.map(r=>[r.id,r]));
const odds=JSON.parse(fs.readFileSync('work/realism-v34/site-odds.json'));
const name=(line,star=3)=>roster[line].forms[star-1].name;
const sourceHash=createHash('sha256').update(JSON.stringify([comps,guides])).digest('hex');
const rows={};
for(const r of comps.rows){
  const cost=roster[r.carry].cost,carry=name(r.carry),roll=r.rollLevel;
  const companions=r.boards.find(b=>b.level===9).team.filter(u=>u.line!==r.carry&&u.star===3&&roster[u.line].cost===cost).map(u=>name(u.line));
  const secondary=companions.length?`Collect ${companions.join(' and ')} alongside it, but finish the carry first.`:'Buy matching-cost secondary upgrades alongside it.';
  const plan=roll
    ?cost===3
      ?`Stabilize ${carry} at 2★ on level ${roll}. Finish its 3★ upgrade only when close; otherwise level to 8 and strengthen the frontline. Keep secondary units at 2★.`
      :`Roll at ${roll} for ${carry} 3★. ${secondary} Once the carry is upgraded, level to 8; keep lower-cost support at 2★ unless it upgraded earlier.`
    :r.category==='legendary'
      ?`Build a 2★ frontline and use your upgraded item holder through level 8. Move toward 9 after stabilizing. Transfer carry items to ${carry} when it improves the board; keep the holder while the legendary is missing.`
      :`Level to 8 and roll for ${carry} 2★ plus a 2★ frontline. Keep your upgraded item holder until the replacement is ready. Add level 9 utility after the level 8 board is stable.`;
  const stop=roll?`After the carry hits, level and keep it. If the chase is still weak at 4-4, stop rolling and build the level 8 bridge.${roll>5?' Do not restart a lower-cost reroll at '+roll+'.':''}`:r.category==='legendary'?`Stabilize at 8 before spending on level 9. A 1★ legendary is a bridge, not the tested 2★ cap.`:`Finish the level 8 carry and tank before pushing 9. Keep an upgraded lower-cost unit over an unfinished replacement.`;
  const stages=guides[r.id].stages.map(s=>{
    const team=s.team.map(u=>({...u,items:[...u.items],star:roster[u.line].cost===5?1:Math.min(u.star,2)}));
    // A completed cheap carry is the continuation after its natural reroll window.
    const primary=team.find(u=>u.line===r.carry);
    if(primary&&roll&&cost<=2&&s.level>roll)primary.star=3;
    const holders=team.filter(u=>u.items.length).map(u=>{
      const h=s.holders.find(h=>h.holder===u.line);
      return {...(h??{holder:u.line,target:u.line,targetStar:u.star,keep:true}),holderStar:u.star,items:[...u.items]};
    });
    const note=s.level< (roll??8)
      ?`Upgrade the frontline and use the item holders shown. Save for ${roll?'the level '+roll+' carry reroll':'level 8'}; buy carry copies along the way.`
      :roll&&s.level===roll?plan
      :roll&&cost<=2?`Keep ${carry} 3★ after the reroll. Add stronger frontline and utility as you level; secondary 3★ upgrades are optional.`
      :plan;
    return {key:s.key,level:s.level,team,holders,note,suggested:true};
  });
  rows[r.id]={plan,stop,stages,odds:odds.rows.filter(o=>o.line===r.carry&&o.goal===(roll?9:3)&&(roll?o.level===roll:true))};
}
applyProgressionPlans(rows);
const result={version:2,rules:34,sourceHash,engineIdentity:odds.identity,study:{fullGames:6848,conditionalTrials:368640,attainedFights:133688,carryOddsTrials:odds.rows.reduce((n,r)=>n+r.n,0)},rows};
fs.writeFileSync('composition-guidance.js','// Suggested progression and native conditional shop results. Generated by scripts/realism/export-site.mjs.\nwindow.KANTO_GUIDANCE='+JSON.stringify(result)+';\n');
console.log(JSON.stringify({compositions:Object.keys(rows).length,progression:Object.values(rows).reduce((n,r)=>n+r.stages.length,0),odds:odds.rows.length,bytes:fs.statSync('composition-guidance.js').size}));
